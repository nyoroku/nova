def build_all():
    for lang_code, dir_name in LANGUAGES:
        target_dir = LOCALE_DIR / dir_name / "LC_MESSAGES"
        target_dir.mkdir(parents=True, exist_ok=True)
        po_path = target_dir / "django.po"
        mo_path = target_dir / "django.mo"

        po = polib.POFile()
        po.metadata = {
            "Project-Id-Version": "Nova 2.0",
            "Report-Msgid-Bugs-To": "",
            "POT-Creation-Date": "2026-09-09 12:00+0300",
            "PO-Revision-Date": "2026-09-09 12:00+0300",
            "Language": lang_code,
            "MIME-Version": "1.0",
            "Content-Type": "text/plain; charset=UTF-8",
            "Content-Transfer-Encoding": "8bit",
        }

        count = 0
        for msgid, translations in TRANSLATIONS.items():
            if lang_code == "en":
                msgstr = msgid
            else:
                key = dir_name if dir_name in translations else lang_code
                msgstr = translations.get(key, msgid)

            entry = polib.POEntry(
                msgid=msgid,
                msgstr=msgstr,
            )
            po.append(entry)
            count += 1

        po.save(str(po_path))
        po.save_as_mofile(str(mo_path))
        print(f"[{lang_code}] Successfully compiled {count} entries into {mo_path}")

if __name__ == "__main__":
    build_all()
